import os

public let pasteLog = Logger(subsystem: "studio.bast.bucket", category: "paste")

/// How a batch is written into the clipboard.
/// `bare` is the default: Claude Code turns every space-separated image path into an attachment,
/// while in `numbered` only the last path became an image (observed 3/3, 2026-10-24).
public enum PasteFormat: String, CaseIterable {
    case bare, numbered, atPaths, lines

    public var title: String {
        switch self {
        case .numbered: return "Numbered with prompt"
        case .bare: return "Bare paths (recommended)"
        case .atPaths: return "@paths"
        case .lines: return "One path per line"
        }
    }

    public static var current: PasteFormat {
        get { PasteFormat(rawValue: UserDefaults.standard.string(forKey: "pasteFormat") ?? "") ?? .bare }
        set { UserDefaults.standard.set(newValue.rawValue, forKey: "pasteFormat") }
    }
}

/// How a path is written into text a shell may read. Three levels, so ordinary paths stay exactly as they were
/// (Claude Code turns bare and double-quoted paths into image attachments) and only odd ones change:
///  1. only plain characters            -> as is
///  2. plain characters plus spaces     -> "double quoted" (as before)
///  3. anything else (`$`, backtick, `"`, `'`, `;`, `&`, parentheses, backslash...) -> every special character gets a backslash, the form Finder produces when
///     you drag a file into a terminal. Not verified against Claude Code yet (see the security notes).
/// Control characters (newline, CR, NUL...) have no safe spelling: the path is not delivered (nil).
public enum ShellQuote {
    private static let plain = CharacterSet.alphanumerics.union(.init(charactersIn: "/._-+@,:%="))

    public static func hasControl(_ p: String) -> Bool {
        p.unicodeScalars.contains { $0.value < 0x20 || $0.value == 0x7F }
    }

    public static func path(_ p: String) -> String? {
        if hasControl(p) { return nil }
        let scalars = p.unicodeScalars
        if scalars.allSatisfy(plain.contains) { return p }
        if scalars.allSatisfy(plain.union(.init(charactersIn: " ")).contains) { return "\"\(p)\"" }
        var out = ""
        for u in scalars {
            if !plain.contains(u) { out.append("\\") }
            out.unicodeScalars.append(u)
        }
        return out
    }
}

/// "Paste copied text with the bucket" (menu). Off unless the user turned it on: with it off Bucket never looks at what
/// you copy, and a copy made while the bucket waits simply replaces it on the clipboard, as always.
public enum CopiedTextSetting {
    public static let key = "copiedTextJoins"

    public static func isEnabled(in defaults: UserDefaults = .standard) -> Bool { defaults.bool(forKey: key) }
    public static func set(_ on: Bool, in defaults: UserDefaults = .standard) { defaults.set(on, forKey: key) }
    public static var enabled: Bool {
        get { isEnabled() }
        set { set(newValue) }
    }

    public static let menuTitle = "Paste copied text with the bucket"
    public static let helpLine = "Terminals: one paste. Other apps: screenshots, then the text."
}

/// Text the user copied while the bucket was waiting on the clipboard. Kept in memory only: never written to disk or to the log.
public struct CopiedText: Equatable {
    public let string: String
    /// The same copy in its formatted forms (RTF, HTML...), so it goes back to the clipboard as it was copied.
    public let rich: [NSPasteboard.PasteboardType: Data]

    /// Copies marked by their app as secret or as not meant for clipboard tools (password managers, generated content):
    /// never read. See nspasteboard.org.
    static let skipped: [NSPasteboard.PasteboardType] = [
        .init("org.nspasteboard.ConcealedType"), .init("org.nspasteboard.TransientType"), .init("org.nspasteboard.AutoGeneratedType"),
    ]
    static let richTypes: [NSPasteboard.PasteboardType] = [.rtf, .rtfd, .html, .URL]
    /// Longer text than this is left alone (it stays your copy, the bucket waits): a paste that size is not a note for the agent.
    public static let maxLength = 100_000
    static let maxRichBytes = 1_000_000

    /// The plain text on `pasteboard`, if it is something a person copied: nil for images and files without text, for
    /// empty or very long text, and for copies their app marked as secret.
    public static func read(from pasteboard: NSPasteboard) -> CopiedText? {
        let types = pasteboard.types ?? []
        guard !types.contains(where: skipped.contains), types.contains(.string) else { return nil }
        guard !types.contains(.fileURL), !types.contains(.png), !types.contains(.tiff) else { return nil }
        guard let string = pasteboard.string(forType: .string), !string.isEmpty, string.count <= maxLength else { return nil }
        var rich: [NSPasteboard.PasteboardType: Data] = [:], bytes = 0
        for type in richTypes where types.contains(type) {
            guard let data = pasteboard.data(forType: type) else { continue }
            bytes += data.count
            rich[type] = data
        }
        return CopiedText(string: string, rich: bytes <= maxRichBytes ? rich : [:])
    }

    /// Puts the copy back on `pasteboard` as the user made it.
    func write(to pasteboard: NSPasteboard) {
        pasteboard.clearContents()
        let item = NSPasteboardItem()
        item.setString(string, forType: .string)
        for (type, data) in rich { item.setData(data, forType: type) }
        pasteboard.writeObjects([item])
    }
}

/// Does a request for the clipboard data mean the user pasted? Apps also read the clipboard for their own reasons (Safari asks
/// for `public.png` when you type a dead-key accent, measured 12:37:21), and that must not empty the bucket.
/// A paste is Cmd held down right now (Cmd+V), or a mouse click a moment ago (Edit > Paste, the context menu) with Option NOT down
/// (Option is the accent key). Anything else is served but not counted.
public enum PasteIntent {
    public static let clickWindow: TimeInterval = 1.5

    public static func counts(commandDown: Bool, optionDown: Bool, secondsSinceClick: TimeInterval) -> Bool {
        if commandDown { return true }
        return !optionDown && secondsSinceClick >= 0 && secondsSinceClick < clickWindow
    }

    /// Right after an app comes to the front the file URL can be read with no paste (the bucket is staged again for that
    /// app, and an app may check it for its Paste menu), and the Cmd that brought the app there (Cmd+Tab, Cmd+click) can
    /// still be down. Within this window a file URL read never counts.
    public static let activationWindow: TimeInterval = 0.5

    /// A file URL read is how apps like T3 Code (Electron) take a paste: they never ask for the PNG, so ignoring it left the
    /// bucket full after every paste (log 2026-11-18). It counts only with Cmd down (Cmd+V) and not right after an app
    /// activated; a click does not count for it, because clicking an app to the front is exactly when the menu-check read comes.
    public static func countsFileURL(commandDown: Bool, secondsSinceActivation: TimeInterval) -> Bool {
        commandDown && secondsSinceActivation >= activationWindow
    }

    /// The live state: global modifier flags and the time since the last mouse-up (no permission needed for either).
    public static func current() -> (command: Bool, option: Bool, sinceClick: TimeInterval) {
        let flags = NSEvent.modifierFlags
        let since = min(CGEventSource.secondsSinceLastEventType(.combinedSessionState, eventType: .leftMouseUp),
                        CGEventSource.secondsSinceLastEventType(.combinedSessionState, eventType: .rightMouseUp))
        return (flags.contains(.command), flags.contains(.option), since)
    }
}

/// Fires `onPasted` at most once, and only for a request that `PasteIntent` says is a paste. A file URL read has its own,
/// stricter rule (`countsFileURL`): desktop apps read it right after activation, before any paste, to validate their Paste menu.
/// A request that does not count is still served; `onIgnored` fires once so the exporter can put a fresh promise back
/// (data that was served is cached by the pasteboard, and the real Cmd+V would never ask again).
private final class PasteGate {
    private let onPasted: () -> Void
    private let intent: () -> (command: Bool, option: Bool, sinceClick: TimeInterval)
    private let sinceActivation: () -> TimeInterval
    var onIgnored: (() -> Void)?
    /// Fires on the main queue for every request, counted or not: the exporter waits for the requests of a paste to
    /// stop before it touches the clipboard again (an app that pastes several files asks for them one by one).
    var onRequest: (() -> Void)?
    var hasFired: Bool { lock.lock(); defer { lock.unlock() }; return fired }
    private var fired = false
    private var ignoredReported = false
    private let lock = NSLock()
    init(_ onPasted: @escaping () -> Void,
         intent: @escaping () -> (command: Bool, option: Bool, sinceClick: TimeInterval) = PasteIntent.current,
         sinceActivation: @escaping () -> TimeInterval = { .infinity }) {
        self.onPasted = onPasted
        self.intent = intent
        self.sinceActivation = sinceActivation
    }
    func requested(_ type: NSPasteboard.PasteboardType) {
        let i = intent()
        let counts: Bool
        if type == .fileURL {
            let since = sinceActivation()
            counts = PasteIntent.countsFileURL(commandDown: i.command, secondsSinceActivation: since)
            pasteLog.notice("gate \(counts ? "counted" : "ignored", privacy: .public) (file url): cmd \(i.command, privacy: .public) since activation \(since, format: .fixed(precision: 2), privacy: .public) s")
        } else {
            counts = PasteIntent.counts(commandDown: i.command, optionDown: i.option, secondsSinceClick: i.sinceClick)
            pasteLog.notice("gate \(counts ? "counted" : "ignored", privacy: .public): cmd \(i.command, privacy: .public) opt \(i.option, privacy: .public) since click \(i.sinceClick, format: .fixed(precision: 2), privacy: .public) s")
        }
        defer { if let onRequest { DispatchQueue.main.async(execute: onRequest) } } // runs after the unlock below
        lock.lock()
        defer { lock.unlock() }
        if counts {
            guard !fired else { return }
            fired = true
            DispatchQueue.main.async(execute: onPasted)
        } else if !fired, !ignoredReported {
            ignoredReported = true
            DispatchQueue.main.async { [onIgnored] in onIgnored?() }
        }
    }
}

/// Lazy data for one pasteboard item.
private final class PastePromise: NSObject, NSPasteboardItemDataProvider {
    private let text: String?
    private let path: String
    private let gate: PasteGate

    init(text: String?, path: String, gate: PasteGate) {
        self.text = text
        self.path = path
        self.gate = gate
    }

    func pasteboard(_ pasteboard: NSPasteboard?, item: NSPasteboardItem, provideDataForType type: NSPasteboard.PasteboardType) {
        Exporter.fill(item, type: type, text: text, path: path)
        pasteLog.notice("clipboard data requested: \(type.rawValue, privacy: .public), front app \(NSWorkspace.shared.frontmostApplication?.bundleIdentifier ?? "?", privacy: .public)")
        gate.requested(type)
    }

    func pasteboardFinishedWithDataProvider(_ pasteboard: NSPasteboard) {}
}

/// Exporter: turns a batch into text and puts it on the clipboard. Never moves or deletes anything.
public final class Exporter {
    private let library: Library
    private let pasteboard: NSPasteboard
    private var staged = false
    /// Pasteboard generation right after our promise went in: if it changed, the clipboard is no longer ours.
    private var stagedChange = -1
    /// The shots of the last batch we put on the clipboard (stage, restage or copy) and the pasteboard generation right after
    /// that write. While the generation is unchanged the clipboard is still ours and the batch can follow the front app.
    private var lastShots: [Shot] = []
    private var lastChange = -1
    /// What the current promise was made from, so an ignored request can put the same promise back.
    private var stagedAll: [Shot] = [], stagedMode = PasteMode.terminal, stagedOnPasted: (() -> Void)?
    private var currentGate: PasteGate?
    /// What the gate reads to tell a paste from an app's own read. Injectable so checks can play both.
    public var pasteIntent: () -> (command: Bool, option: Bool, sinceClick: TimeInterval) = PasteIntent.current
    /// Seconds since an app last came to the front (see `PasteIntent.countsFileURL`). Injectable for the checks.
    public lazy var secondsSinceActivation: () -> TimeInterval = { [weak self] in
        guard let at = self?.lastActivation else { return .infinity }
        return Date().timeIntervalSince(at)
    }
    private var lastActivation: Date?
    private var activationObserver: NSObjectProtocol?
    /// Text the user copied while the bucket waited on the clipboard ("Paste copied text with the bucket"). It travels with
    /// the bucket: in a terminal it is pasted right after the paths, in the same paste; in a browser or an app the
    /// screenshots are pasted first and the text goes back on the clipboard for the next paste. Memory only.
    public private(set) var copiedText: CopiedText?
    /// Whether a copy made while the bucket waits joins it. Injectable for the checks.
    public var copiedTextJoins: () -> Bool = { CopiedTextSetting.enabled }
    /// The user's copy was taken: the app stages the bucket again, with what it holds now, and says so.
    public var onCopiedText: (() -> Void)?
    /// The screenshots were pasted in a browser or an app and the copied text is back on the clipboard.
    public var onTextReturned: (() -> Void)?
    /// How often the clipboard's change count is read while the bucket waits (a number: no data is read for it).
    public static let clipboardPollInterval: TimeInterval = 0.25
    /// The text goes back this long after the last request of the paste (an app asks for several files one by one).
    public static let textReturnDelay: TimeInterval = 0.4
    private var clipboardTimer: DispatchSourceTimer?
    private var textReturn: DispatchWorkItem?
    private var restageTimes: [Date] = []
    /// At most this many fresh promises per second: if something keeps asking, the loop stops (the bucket stays loaded: fail safe).
    public static let maxRestagesPerSecond = 5

    /// `pasteboard` is injectable so checks never touch the real clipboard.
    public init(library: Library, pasteboard: NSPasteboard = .general) {
        self.library = library
        self.pasteboard = pasteboard
        activationObserver = NSWorkspace.shared.notificationCenter.addObserver(
            forName: NSWorkspace.didActivateApplicationNotification, object: nil, queue: .main) { [weak self] _ in
            self?.lastActivation = Date()
        }
    }

    deinit {
        if let activationObserver { NSWorkspace.shared.notificationCenter.removeObserver(activationObserver) }
        clipboardTimer?.cancel()
        textReturn?.cancel()
    }

    /// What a bucket item becomes when pasted: a photo is its png; a recording is its frames in order and then its json
    /// (the agent attaches the frames as images and reads the json on its own). Where only images go (browser, app) the json stays out.
    public static func deliveryPaths(_ shot: Shot, includeJSON: Bool = true) -> [String] {
        guard let r = shot.recording else { return [shot.path] }
        return includeJSON ? r.frames + [r.sidecar] : r.frames
    }

    /// Only shots whose png is still on disk: a path that does not exist is never handed to the clipboard (logged, nothing deleted).
    /// A recording needs every frame and its json.
    public static func deliverable(_ shots: [Shot]) -> [Shot] {
        shots.filter { shot in
            let paths = deliveryPaths(shot)
            if paths.contains(where: ShellQuote.hasControl) {
                NSLog("Bucket: skipped \(shot.id) from the clipboard (its path has control characters)")
                return false
            }
            let there = paths.allSatisfy { FileManager.default.fileExists(atPath: $0) }
            if !there { NSLog("Bucket: skipped \(shot.id) from the clipboard (a file is missing near \(shot.path))") }
            return there
        }
    }

    public static func render(_ shots: [Shot], format: PasteFormat) -> String {
        // A path that cannot be written safely (control characters) never reaches the clipboard, in any format.
        let paths = shots.flatMap { deliveryPaths($0) }.filter { p in
            let ok = ShellQuote.path(p) != nil
            if !ok { NSLog("Bucket: skipped a path from the clipboard (it has control characters)") }
            return ok
        }
        let quoted = paths.compactMap { ShellQuote.path($0) }
        switch format {
        case .numbered:
            let noun = quoted.count == 1 ? "this screenshot" : "these screenshots in order"
            let list = quoted.enumerated().map { "\($0.offset + 1). \($0.element)" }.joined(separator: "\n")
            return "Read \(noun):\n\(list)\n"
        case .bare: return quoted.joined(separator: " ") + " "
        case .atPaths: return quoted.map { "@\($0)" }.joined(separator: " ") + " "
        case .lines: return quoted.joined(separator: "\n") + "\n"
        }
    }

    /// The pasteboard types offered for each mode.
    public static func types(for mode: PasteMode) -> [NSPasteboard.PasteboardType] {
        switch mode {
        case .terminal: return [.string]
        case .browser: return [.png]
        case .app: return [.fileURL, .png]
        }
    }

    /// Does a promise for this mode stay on this Mac (no Universal Clipboard)? Yes when it offers a file URL: macOS asks
    /// for a promised file URL the moment it is written, to have the file ready for your other devices (measured
    /// 2026-11-18: `pboard` asks ~30 ms after the write, with any app in front and no key down; text and PNG promises
    /// are left alone). The pasteboard keeps that answer, so the real ⌘V of an app that pastes files (T3 Code, Electron)
    /// read the kept copy and never reached the data provider: the bucket stayed full. A promise that stays on this Mac
    /// is not read ahead, and the first request for the file URL is the paste itself.
    public static func staysOnThisMac(_ mode: PasteMode) -> Bool { types(for: mode).contains(.fileURL) }

    static let transientMarker = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
    static let autoGeneratedMarker = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")

    fileprivate static func fill(_ item: NSPasteboardItem, type: NSPasteboard.PasteboardType, text: String?, path: String) {
        switch type {
        case .string: if let text { item.setString(text, forType: .string) }
        case .fileURL: item.setString(URL(fileURLWithPath: path).absoluteString, forType: .fileURL)
        case .png: if let data = try? Data(contentsOf: URL(fileURLWithPath: path)) { item.setData(data, forType: .png) }
        default: break
        }
    }

    /// The pasteboard items for a batch (already filtered with `deliverable`). Terminal: one item with the rendered text.
    /// Browser and app: one item per screenshot. With a `gate` the data is lazy; without, it is written now.
    /// Lazy items also carry the clipboard-manager markers, so history tools skip our churn.
    /// `copied` is text the user copied meanwhile: in the terminal layout it follows the paths (every paste format ends in a
    /// space or a new line). The other layouts cannot carry it: it goes back on the clipboard after the paste.
    private func items(for shots: [Shot], mode: PasteMode, gate: PasteGate?, copied: String? = nil) -> [NSPasteboardItem] {
        let types = Exporter.types(for: mode)
        let units: [(text: String?, path: String)] = mode == .terminal
            ? [(Exporter.render(shots, format: .current) + (copied ?? ""), shots[0].path)]
            : shots.flatMap { Exporter.deliveryPaths($0, includeJSON: false) }.map { (nil, $0) }
        return units.map { unit in
            let item = NSPasteboardItem()
            if let gate {
                item.setDataProvider(PastePromise(text: unit.text, path: unit.path, gate: gate), forTypes: types)
                item.setData(Data(), forType: Exporter.transientMarker)
                item.setData(Data(), forType: Exporter.autoGeneratedMarker)
            } else {
                for type in types { Exporter.fill(item, type: type, text: unit.text, path: unit.path) }
            }
            return item
        }
    }

    /// Puts the whole bucket on the clipboard as a promise. `onPasted` fires once, the first time something
    /// asks for the data during a paste (normally your ⌘V). A file URL read counts only with Cmd down and not right after an
    /// app came to the front (`PasteIntent.countsFileURL`); a promise that offers one stays on this Mac (`staysOnThisMac`).
    public func stage(_ all: [Shot], mode: PasteMode = .terminal, onPasted: @escaping () -> Void) {
        let shots = Exporter.deliverable(all)
        guard !shots.isEmpty else { return }
        let pb = pasteboard
        if Exporter.staysOnThisMac(mode) { pb.prepareForNewContents(with: .currentHostOnly) } else { pb.clearContents() }
        let gate = PasteGate(onPasted, intent: pasteIntent, sinceActivation: secondsSinceActivation)
        gate.onIgnored = { [weak self, weak gate] in self?.promiseServedEarly(gate) }
        gate.onRequest = { [weak self, weak gate] in self?.requestSeen(gate) }
        currentGate = gate
        stagedAll = all; stagedMode = mode; stagedOnPasted = onPasted
        textReturn?.cancel(); textReturn = nil
        pb.writeObjects(items(for: shots, mode: mode, gate: gate, copied: copiedText?.string))
        staged = true
        stagedChange = pb.changeCount
        lastShots = shots
        lastChange = pb.changeCount
        watchClipboard()
    }

    // MARK: Copied text

    /// Reads the clipboard's change count while the bucket waits on it, only with "Paste copied text with the bucket" on.
    /// Stops by itself once the bucket was pasted, unstaged, or replaced by a copy that cannot join.
    private func watchClipboard() {
        guard clipboardTimer == nil, copiedTextJoins() else { return }
        let timer = DispatchSource.makeTimerSource(queue: .main)
        timer.schedule(deadline: .now() + Exporter.clipboardPollInterval, repeating: Exporter.clipboardPollInterval, leeway: .milliseconds(50))
        timer.setEventHandler { [weak self] in self?.checkClipboard() }
        clipboardTimer = timer
        timer.resume()
    }

    private func stopClipboardWatch() { clipboardTimer?.cancel(); clipboardTimer = nil }

    /// True while the clipboard is being watched for a copy (for the checks).
    public var isWatchingClipboard: Bool { clipboardTimer != nil }

    /// Looks at the clipboard while the bucket waits on it (the timer calls this; public for the checks). If someone else
    /// wrote it and it is plain text a person copied, the text is taken and `onCopiedText` lets the app stage the bucket
    /// again with it. Anything else (an image, a file, a secret, the switch off) is left exactly as it is: that copy wins,
    /// as it always did.
    public func checkClipboard() {
        guard staged, let gate = currentGate, !gate.hasFired else { stopClipboardWatch(); return }
        guard pasteboard.changeCount != stagedChange else { return } // still our promise
        stopClipboardWatch()
        guard copiedTextJoins(), let text = CopiedText.read(from: pasteboard) else {
            copiedText = nil // an earlier text was part of the promise this copy replaced
            return
        }
        copiedText = text
        pasteLog.notice("copied text joins the bucket (\(text.string.count, privacy: .public) characters)")
        onCopiedText?()
        if !isStaged { copiedText = nil } // nobody staged it (the bucket emptied meanwhile): the copy stays where it is
    }

    /// A request for the staged data arrived. Once the paste was counted, the text that could not travel with it (browser
    /// and app layouts) goes back on the clipboard, after the requests of that paste have stopped.
    private func requestSeen(_ gate: PasteGate?) {
        guard let gate, gate === currentGate, gate.hasFired else { return }
        stopClipboardWatch()
        guard copiedText != nil else { return }
        if stagedMode == .terminal { copiedText = nil; return } // it went out with the paths
        textReturn?.cancel()
        let work = DispatchWorkItem { [weak self] in self?.returnTextAfterPaste() }
        textReturn = work
        DispatchQueue.main.asyncAfter(deadline: .now() + Exporter.textReturnDelay, execute: work)
    }

    private func returnTextAfterPaste() {
        textReturn = nil
        guard let text = copiedText else { return }
        copiedText = nil
        guard pasteboard.changeCount == lastChange else { return } // something was copied since: that stays
        text.write(to: pasteboard)
        staged = false
        pasteLog.notice("copied text back on the clipboard after the paste")
        onTextReturned?()
    }

    /// "Paste copied text with the bucket" was turned off: a text that was travelling with the bucket goes back on the
    /// clipboard as the plain copy it was, and the bucket waits without the clipboard, as it does with the switch off.
    public func releaseCopiedText() {
        stopClipboardWatch()
        textReturn?.cancel(); textReturn = nil
        guard let text = copiedText else { return }
        copiedText = nil
        guard isStaged || pasteboard.changeCount == lastChange else { return }
        text.write(to: pasteboard)
        staged = false
    }

    // MARK: -

    /// A request that was not a paste got the data: the clipboard now holds it, so put a fresh promise where it was.
    /// Only if the clipboard is still ours (never over something the user copied) and the gate is still the current one.
    private func promiseServedEarly(_ gate: PasteGate?) {
        guard let gate, gate === currentGate, isStaged, let onPasted = stagedOnPasted else {
            pasteLog.notice("promise not restaged (clipboard no longer ours)")
            return
        }
        let now = Date()
        restageTimes = restageTimes.filter { now.timeIntervalSince($0) < 1 }
        guard restageTimes.count < Exporter.maxRestagesPerSecond else {
            pasteLog.notice("promise not restaged (too many requests in a second)")
            return
        }
        restageTimes.append(now)
        pasteLog.notice("promise restaged after an ignored request")
        stage(stagedAll, mode: stagedMode, onPasted: onPasted)
    }

    /// Lays the last batch out again for another front app while the clipboard is still our last write (nobody copied
    /// anything since). Lazy like `stage`, with the same items and markers, but no paste action: the batch was already
    /// pasted or recorded, so `onPasted` must not fire again. Returns whether it wrote.
    @discardableResult
    public func relayout(mode: PasteMode) -> Bool {
        guard !lastShots.isEmpty, pasteboard.changeCount == lastChange else { return false }
        let shots = Exporter.deliverable(lastShots)
        guard !shots.isEmpty else { return false }
        let pb = pasteboard
        pb.clearContents()
        pb.writeObjects(items(for: shots, mode: mode, gate: PasteGate({}, intent: pasteIntent)))
        lastChange = pb.changeCount
        return true
    }

    /// Stages again for another front app, but only while our promise is still what the clipboard holds:
    /// something the user copied in the meantime is never replaced. Returns whether it re-staged.
    @discardableResult
    public func restage(_ all: [Shot], mode: PasteMode, onPasted: @escaping () -> Void) -> Bool {
        guard isStaged else { return false }
        stage(all, mode: mode, onPasted: onPasted)
        return true
    }

    /// True while the clipboard still holds the promise we made (nobody copied anything since).
    public var isStaged: Bool { staged && pasteboard.changeCount == stagedChange }

    /// The bucket lost shots (removed, cleared, sent to the Desktop): a promise made for the old content must not
    /// paste them. Clears the clipboard only if our promise is still what it holds; anything the user copied since stays.
    public func unstage() {
        defer { staged = false; lastShots = []; copiedText = nil; stopClipboardWatch() }
        guard isStaged else { return }
        // Text the user copied was travelling with the bucket: it goes back as the copy it was, never lost.
        if let text = copiedText { text.write(to: pasteboard) } else { pasteboard.clearContents() }
    }

    /// Copies eagerly (no promise) and records the batch.
    public func copy(_ all: [Shot], mode: PasteMode = .terminal, recopy: Bool = false) {
        let shots = Exporter.deliverable(all)
        guard !shots.isEmpty else { return }
        staged = false
        copiedText = nil // "Copy batch" is the screenshots, as always: text copied meanwhile is replaced, as it was before
        textReturn?.cancel(); textReturn = nil
        stopClipboardWatch()
        let pb = pasteboard
        pb.clearContents()
        pb.writeObjects(items(for: shots, mode: mode, gate: nil))
        lastShots = shots
        lastChange = pb.changeCount
        record(shots, via: recopy ? "recopy" : "copy")
    }

    /// `copiedAt`, not `sentAt`: we know the text left the clipboard, not that the agent read it.
    public func record(_ shots: [Shot], via: String) {
        let batchID = UUID().uuidString.prefix(8).lowercased()
        let record: [String: Any] = [
            "batchId": String(batchID),
            "copiedAt": ISO8601DateFormatter().string(from: Date()),
            "via": via,
            "format": PasteFormat.current.rawValue,
            "ids": shots.map(\.id),
        ]
        appendLine(record, to: library.root.appendingPathComponent("batches.jsonl"))

        // Read-modify-write on the disk copy: the Shot we hold may be stale (OCR can have written since).
        for shot in shots where shot.recording == nil { // a recording's json is the agent's, not a Shot: it holds no batch list
            do { try library.update(sidecar: shot.sidecarPath) { $0.batches.append(String(batchID)) } }
            catch { NSLog("Bucket: could not record batch \(batchID) on \(shot.id): \(error.localizedDescription)") }
        }
    }

    private func appendLine(_ object: [String: Any], to url: URL) {
        guard var data = try? JSONSerialization.data(withJSONObject: object, options: [.sortedKeys, .withoutEscapingSlashes])
        else { return }
        data.append(0x0A)
        if let handle = try? FileHandle(forWritingTo: url) {
            handle.seekToEndOfFile()
            handle.write(data)
            try? handle.close()
        } else {
            try? data.write(to: url)
        }
    }
